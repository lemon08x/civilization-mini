function harvestStorage(id:string,edible:boolean):string {
 if(!edible)return '干燥通风，按纤维用途、含水状态与品质分批存放；不作食用储备。';
 if(['wheat','soy','crop-rice','crop-foxtail','crop-broomcorn','crop-barley','crop-adzuki','crop-buckwheat','crop-maize'].includes(id))return '籽粒干燥后防潮防虫，种用与食用分批；脱壳、磨粉后重新考虑保存条件。';
 if(['crop-sesame','crop-peanut'].includes(id))return '健康原料充分干燥、防潮，留意油脂异味与霉变；不可把炒制当作霉变补救。';
 if(['crop-mallow','crop-mustard','crop-cabbage','crop-spinach'].includes(id))return '鲜叶优先处理，注意失水、挤压与腐败；干制和腌渍另需相应工艺。';
 if(['crop-turnip','crop-radish','crop-carrot'].includes(id))return '根叶分别安排，挑出伤损并按温湿度管理；留种植株不等同食用根的存放。';
 if(id==='crop-potato')return '避光、通风，分开种用与食用；发绿、严重萌芽或腐坏批次不进入普通食谱。';
 if(id==='crop-sweetpotato')return '挑完好健康块根，注意低温伤害与腐烂；留种薯单独安排。';
 if(id==='crop-waxgourd')return '完整老熟果与伤果分开，切开后优先处理；耐储不表示无限保鲜。';
 if(id==='crop-chili')return '鲜果及时处理，干制另选适宜天气与洁净条件，干椒须防潮。';
 return '按成熟度分批，避免挤压并及时处理伤果；完整果与切开果不共用保存期限。';
}
